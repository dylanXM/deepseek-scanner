"""Report rendering: Markdown evidence report + JSON (AI-BOM style).

Every report carries the detection-limits statement. The wording is
deliberate: findings are evidence of presence; a clean scan is the
absence of known indicators, nothing more.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone

from . import __version__
from .rules import RuleSet
from .scanner import SEVERITY_ORDER, ScanResult

LIMITATIONS = (
    "This scanner checks a fixed, published set of textual and filename "
    "indicators. It detects, when present in the scanned tree: references "
    "to DeepSeek-hosted API endpoints in source and configuration; "
    "DeepSeek SDK imports and package names; DeepSeek names in dependency "
    "manifests and lockfiles (direct and transitive); DeepSeek image or "
    "model pulls in container definitions; and first-party model weight "
    "files and model configs.\n\n"
    "It cannot detect: a model distilled from DeepSeek outputs and "
    "shipped under a different name with no textual trace; weight files "
    "that were renamed and stripped of identifying metadata; calls routed "
    "through a third-party gateway under that gateway's own domains and "
    "model names; or any use that leaves no artifact in the scanned tree.\n\n"
    "A report with findings is evidence that the listed indicators are "
    "present at the listed locations. A report without findings means "
    "only that none of the indicators in the current rule set were found "
    "in the scanned tree; it is not proof that no DeepSeek-derived "
    "component exists in a product. Determinations about obligations "
    "under DHS Exclusion and Removal Order #2026-01 or FAR 52.204-30 "
    "rest with each organization and its counsel. This tool is an "
    "evidence-collection aid, not a legal determination."
)


def _timestamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def to_json_dict(result: ScanResult, ruleset: RuleSet) -> dict:
    counts = result.counts_by_severity()
    return {
        "tool": {"name": "deepseek-exposure-scan", "version": __version__},
        "rules_version": ruleset.rules_version,
        "scan": {
            "target": result.target,
            "timestamp_utc": _timestamp(),
            "files_scanned": result.files_scanned,
        },
        "summary": {"total_findings": len(result.findings), "by_severity": counts},
        "findings": [
            {
                "rule_id": f.rule_id,
                "rule_name": f.rule_name,
                "severity": f.severity,
                "component": {
                    "name": f.component_name,
                    "type": f.component_type,
                    "vendor": "DeepSeek",
                },
                "evidence": {
                    "type": f.evidence_type,
                    "source_file": f.file,
                    "line": f.line,
                    "snippet": f.snippet,
                },
                "regulatory_context": f.fascsa_note,
                "remediation": f.remediation,
            }
            for f in result.findings
        ],
        "limitations": LIMITATIONS,
    }


def render_json(result: ScanResult, ruleset: RuleSet) -> str:
    return json.dumps(to_json_dict(result, ruleset), indent=2, ensure_ascii=False) + "\n"


def render_markdown(result: ScanResult, ruleset: RuleSet) -> str:
    counts = result.counts_by_severity()
    out: list[str] = []
    out.append("# DeepSeek Exposure Scan - Evidence Report")
    out.append("")
    out.append(
        "Generated by `deepseek-scan` "
        f"(tool v{__version__}, rules v{ruleset.rules_version})."
    )
    out.append("")
    out.append("| Field | Value |")
    out.append("|---|---|")
    out.append(f"| Scan target | `{result.target}` |")
    out.append(f"| Timestamp (UTC) | {_timestamp()} |")
    out.append(f"| Files scanned | {result.files_scanned} |")
    out.append(f"| Total findings | {len(result.findings)} |")
    out.append("")
    out.append(
        "This report lists indicators of DeepSeek components found in the "
        "scanned tree, with file-and-line evidence, so the results can be "
        "handed to an engineering, security or contracts team for review "
        "and remediation. Read the **Detection limits** section before "
        "drawing conclusions from it."
    )
    out.append("")
    out.append("## Summary by severity")
    out.append("")
    if counts:
        out.append("| Severity | Findings |")
        out.append("|---|---|")
        for sev in sorted(counts, key=lambda s: SEVERITY_ORDER.get(s, 99)):
            out.append(f"| {sev} | {counts[sev]} |")
    else:
        out.append("No findings.")
    out.append("")
    out.append("## Findings")
    out.append("")
    if not result.findings:
        out.append(
            "No indicators from the current rule set were found in the "
            "scanned tree. This is a statement about the indicators in "
            f"rules v{ruleset.rules_version} only - see **Detection "
            "limits** below for what a scan cannot rule out."
        )
        out.append("")
    else:
        current_sev = None
        for f in result.findings:
            if f.severity != current_sev:
                current_sev = f.severity
                out.append(f"### {current_sev.capitalize()}")
                out.append("")
            loc = f"`{f.file}:{f.line}`" if f.line else f"`{f.file}`"
            out.append(f"#### {f.rule_name} ({f.rule_id})")
            out.append("")
            out.append(f"- Location: {loc}")
            out.append(f"- Component: {f.component_name} ({f.component_type})")
            out.append(f"- Evidence type: {f.evidence_type}")
            out.append("")
            out.append("```")
            out.append(f.snippet)
            out.append("```")
            out.append("")
            if f.fascsa_note:
                out.append(f"Regulatory context: {f.fascsa_note}")
                out.append("")
            if f.remediation:
                out.append(f"Suggested remediation: {f.remediation}")
                out.append("")
    out.append("## Detection limits")
    out.append("")
    out.append(LIMITATIONS)
    out.append("")
    return "\n".join(out)
